"""The billing agent's decisions: what each invoice says, whether a delivery meets the
contract, and what a reminder says. Money-facing actions only run after a person approves."""
from __future__ import annotations

from datetime import date, timedelta
from decimal import Decimal
from typing import Optional

from pydantic import BaseModel, Field

from .llm import generate_json
from .schedule import Milestone, Schedule

NET_TERMS = {10: "NET_10", 15: "NET_15", 30: "NET_30", 45: "NET_45", 60: "NET_60", 90: "NET_90"}


def _cite_line(label: str, page: Optional[int], quote: str, limit: int) -> str:
    q = " ".join(quote.split())
    room = max(0, limit - len(label) - 16)
    if len(q) > room:
        q = q[: max(0, room - 3)].rstrip() + "..."
    return f'{label}, page {page}: "{q}"'


def invoice_payload(s: Schedule, m: Milestone, *, invoice_number: str, recipient_email: str,
                    invoice_date: date, invoicer_email: str | None = None) -> dict:
    """The PayPal Invoicing v2 body for one milestone. Every line points at the contract."""
    if not m.amount:
        raise ValueError(f"{m.code} has no readable amount; fix it before invoicing.")
    ref = s.contract_reference or s.contract_title
    detail: dict = {
        "invoice_number": invoice_number,
        "reference": ref[:120],
        "currency_code": m.currency,
        "invoice_date": invoice_date.isoformat(),
        "note": _cite_line(f"Billed under {ref}, milestone {m.code}", m.payment_cite.page,
                           m.payment_cite.quote, 4000),
        "memo": f"Generated by Clause & Pay from {s.contract_title}.",
    }
    if s.payment_terms:
        detail["term"] = _cite_line("Payment terms", s.payment_terms.cite.page, s.payment_terms.cite.quote, 4000)
    if s.net_days and s.net_days in NET_TERMS:
        detail["payment_term"] = {"term_type": NET_TERMS[s.net_days]}
    elif s.net_days:
        detail["payment_term"] = {"term_type": "DUE_ON_DATE_SPECIFIED",
                                  "due_date": (invoice_date + timedelta(days=s.net_days)).isoformat()}
    else:
        detail["payment_term"] = {"term_type": "DUE_ON_RECEIPT"}
    invoicer: dict = {"business_name": s.supplier_name[:300]}
    if invoicer_email:
        invoicer["email_address"] = invoicer_email
    return {
        "detail": detail,
        "invoicer": invoicer,
        "primary_recipients": [{"billing_info": {"business_name": s.client_name[:300],
                                                 "email_address": recipient_email}}],
        "items": [{
            "name": f"{m.code}: {m.name}"[:200],
            "description": _cite_line("Contract", m.payment_cite.page, m.payment_cite.quote, 1000),
            "quantity": "1",
            "unit_amount": {"currency_code": m.currency, "value": str(Decimal(m.amount).quantize(Decimal("0.01")))},
            "unit_of_measure": "AMOUNT",
        }],
        "configuration": {"allow_tip": False, "partial_payment": {"allow_partial_payment": False}},
    }


# ---- delivery check ----


class CriterionResult(BaseModel):
    criterion: str
    met: str = Field(description="yes, no or unclear")
    evidence: str = Field(description="What in the delivery note shows it, or what is missing. Short.")


class DeliveryCheck(BaseModel):
    recommendation: str = Field(description="send or hold")
    criteria: list[CriterionResult]
    summary: str = Field(description="One or two plain sentences for the supplier.")


CHECK_PROMPT = """You help a supplier decide whether to invoice a contract milestone now.
The contract says this milestone ({code}: {name}) must meet these acceptance criteria
(contract page {page}): "{quote}"

Criteria list:
{criteria}

The contract's payment schedule, in order (use it when a criterion refers to other milestones):
{schedule}

{condition}

The supplier's delivery note:
---
{evidence}
---

For each criterion say yes, no or unclear based ONLY on the delivery note. Judge the meaning,
not the exact words: a note that states the same thing in other words meets the criterion.
Use unclear only when the note does not say enough to decide. Recommend "send"
only when every criterion is yes and any invoicing condition is met; otherwise "hold".
Never assume facts that the note does not state."""


async def check_delivery(s: Schedule, m: Milestone, evidence: str) -> DeliveryCheck:
    cond = ""
    if s.invoice_condition:
        cond = (f'Invoicing condition (page {s.invoice_condition.cite.page}): '
                f'"{s.invoice_condition.cite.quote}"')
    acc = m.acceptance_cite
    prompt = CHECK_PROMPT.format(
        code=m.code, name=m.name, page=acc.page if acc else "?", quote=acc.quote if acc else "(not quoted)",
        criteria="\n".join(f"- {c}" for c in m.acceptance_criteria) or "- (none listed)",
        schedule="\n".join(f"- {x.code}: {x.name}" + (" (this milestone)" if x.code == m.code else "")
                            + (" (the last milestone)" if i == len(s.milestones) - 1 else "")
                            for i, x in enumerate(s.milestones)) or "- (not listed)",
        condition=cond, evidence=(evidence or "(no delivery note given)")[:6000])
    out = await generate_json(prompt, DeliveryCheck)
    rec = out.recommendation.strip().lower()
    if rec != "send" or any(c.met.strip().lower() != "yes" for c in out.criteria):
        out.recommendation = "hold"
    else:
        out.recommendation = "send"
    return out


# ---- reminders ----


def days_overdue(due: date, today: date) -> int:
    return max(0, (today - due).days)


def late_interest(amount: str, monthly_rate_pct: Optional[Decimal], days: int) -> Optional[str]:
    """Simple interest for the days overdue at a monthly rate (30-day months). None if no rate."""
    if not monthly_rate_pct or days <= 0:
        return None
    v = Decimal(amount) * monthly_rate_pct / Decimal(100) * Decimal(days) / Decimal(30)
    return str(v.quantize(Decimal("0.01")))


def reminder_text(s: Schedule, m: Milestone, *, invoice_number: str, due: date, today: date,
                  monthly_rate_pct: Optional[Decimal] = None) -> tuple[str, str]:
    """Subject and note for an overdue invoice, quoting the contract's own terms."""
    days = days_overdue(due, today)
    subject = f"Reminder: invoice {invoice_number} for {m.code} is {days} days overdue"
    lines = [
        f"Invoice {invoice_number} for milestone {m.code} ({m.name}), {m.currency} {m.amount}, "
        f"was due on {due.isoformat()} and is {days} days overdue.",
    ]
    if s.payment_terms:
        lines.append(_cite_line("Payment terms", s.payment_terms.cite.page, s.payment_terms.cite.quote, 600))
    if s.late_payment:
        lines.append(_cite_line("Late payment", s.late_payment.cite.page, s.late_payment.cite.quote, 600))
        interest = late_interest(m.amount or "0", monthly_rate_pct, days)
        if interest:
            lines.append(f"Interest accrued to date under that clause: {m.currency} {interest}.")
    lines.append("If you have already paid, please ignore this reminder.")
    return subject, "\n\n".join(lines)


def monthly_rate_from(s: Schedule) -> Optional[Decimal]:
    """1.5 from '... at the rate of 1.5% per month ...' in the late-payment clause, else None."""
    import re
    if not s.late_payment:
        return None
    m = re.search(r"(\d+(?:\.\d+)?)\s*%\s*(?:per|a|each)\s*month", s.late_payment.cite.quote, re.I)
    return Decimal(m.group(1)) if m else None
